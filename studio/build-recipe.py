#!/usr/bin/env python3
"""Write agent/recipes/studio.yaml: the sticker trader recipe plus the Studio section.

The trader's protocol is long and has already drifted from a copy once (devcon-workshop#27), so
studio.yaml is trader.yaml with five exact-text edits, not a second hand-kept recipe. Each edit
fails loudly if its anchor is missing from trader.yaml, so a trader change that moves an anchor
cannot silently produce a Studio recipe without its permissions.

    python3 studio/build-recipe.py            write agent/recipes/studio.yaml
    python3 studio/build-recipe.py --check    exit 1 if the committed file differs (CI)
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TRADER = ROOT / "agent/recipes/trader.yaml"
SECTION = ROOT / "studio/prompt-section.txt"
OUT = ROOT / "agent/recipes/studio.yaml"

TITLE = "title: Devcon 8 sticker trader\n"
DESC_START = "description: >\n"
DESC_END = "parameters:\n"
STUDIO_DESC = (
    "description: >\n"
    "  The sticker trader (same protocol, same payment modes) that can also write terms for your sales\n"
    "  in words, rehearse them over past sales and switch them on. Runs only in the Studio layer\n"
    "  (studio/README.md), which adds the terms-pack-author skill and the `terms` commands.\n"
)
FORBID = "  Stay inside your home directory. Do not curl anything, install anything or read other files.\n"
ALLOW = (
    "  Stay inside your home directory. Do not curl anything, install anything or read other files,\n"
    "  except the two skills named here and the files `terms` writes under ~/studio.\n"
)
START = "  Start: read the deal skill, "
# Studio only: the agent does not start the mailbox wait on its own. Steps 1-3 need no mailbox, and a turn
# stuck in `mbx wait` holds the person's words back, so it waits only once the person asks to sell (or a
# purchase starts). trader.yaml, and so `devcon8 trade`, is unchanged.
KEEP_OLD = (
    "Your first `mbx me` and the\n"
    "  start-up prompt are not a reason to stop: right after you tell your user the address, go straight\n"
    "  to `mbx wait`. The one\n"
)
KEEP_NEW = (
    "Once your user has asked you to sell, or you have started a purchase, your first `mbx me` and each\n"
    "  finished deal are not a reason to stop: go straight back to `mbx wait`. Before your user asks you to\n"
    "  sell, do not run `mbx wait` at all (see Start below). The one\n"
)
WAIT_OLD = "Then wait for buyers with `mbx wait` in the foreground and keep waiting; sell to every participant who asks.{% endif %}"
WAIT_NEW = (
    "Then ask me, in one short sentence, whether I want to write and rehearse terms for my\n"
    "  sales or sell stickers now. Do NOT run `mbx wait` and do not wait for buyers yet: end your turn and\n"
    "  let me answer. Only when I ask you to sell, tell me you are waiting for buyers, then wait with `mbx\n"
    "  wait` in the foreground and keep waiting as above; sell to every participant who asks.{% endif %}"
)


def once(text, anchor, what):
    if text.count(anchor) != 1:
        sys.exit(f"build-recipe: {what} not found exactly once in {TRADER.name}; update studio/build-recipe.py")


def build(t, section):
    once(t, TITLE, "the title line")
    once(t, FORBID, "the home-directory sentence")
    once(t, START, "the Start line")
    once(t, DESC_START, "the description")
    once(t, DESC_END, "the parameters block")
    once(t, KEEP_OLD, "the keep-waiting sentence")
    once(t, WAIT_OLD, "the wait-for-buyers sentence")
    t = t.replace(TITLE, "title: Devcon 8 sticker trader with Terms Pack Studio\n")
    a, b = t.index(DESC_START), t.index(DESC_END)
    if b < a:
        sys.exit(f"build-recipe: the parameters block comes before the description in {TRADER.name}")
    t = t[:a] + STUDIO_DESC + t[b:]
    t = t.replace(FORBID, ALLOW)
    t = t.replace(KEEP_OLD, KEEP_NEW).replace(WAIT_OLD, WAIT_NEW)
    t = t.replace(START, section + "\n" + START)
    return ("# Generated by studio/build-recipe.py from trader.yaml and studio/prompt-section.txt: do not edit.\n" + t)


def main():
    out = build(TRADER.read_text(), SECTION.read_text())
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != out:
            sys.exit("agent/recipes/studio.yaml is stale: run python3 studio/build-recipe.py")
        return
    OUT.write_text(out)


if __name__ == "__main__":
    main()
